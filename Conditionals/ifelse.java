public class ifelse {
    
    public static void main(String[] args){

        int x = 11;
        if (x > 10 && x <= 20)
            System.out.print("Hello");
        else
            System.out.println("bye");
        

        // Max of two numbers
        int a = 10, b = 15;

        if (a > b){
            System.out.println(a);
        } else {
            System.out.println(b);
        }

    }
}
